#!/usr/bin/env bash
# Regenerate every render, STL, calculation output and clash report of hardware/mechanical/.
# Needs OpenSCAD 2021.01, xvfb-run, python3 + numpy + matplotlib; KiCad 9 pcbnew (python3) to refresh
# board_parts.scad from the PCBs (skipped with a warning if pcbnew is missing).  ~6 min on 4 cores.
set -eu
cd "$(dirname "$0")"
mkdir -p renders stl
if python3 -c "import pcbnew" 2>/dev/null; then python3 extract_board_parts.py 2>&1 | grep -v Debug; \
else echo "WARNING: pcbnew not found, using the committed board_parts.scad"; fi
S="xvfb-run -a openscad --colorscheme=Tomorrow"
$S -o renders/assembly.png     --imgsize=1200,900 --camera=118,-136,104,0,0,17 -D 'view="assembly"' dial_spinner.scad
$S -o renders/exploded.png     --imgsize=1200,900 --camera=380,-390,380,25,20,96 -D 'view="exploded"' dial_spinner.scad
$S -o renders/board_bottom.png --imgsize=1200,900 --camera=0,-30,-165,0,0,28 -D 'view="board_bottom"' dial_spinner.scad
$S -o renders/base_top.png     --imgsize=1200,900 --camera=0,-20,160,0,0,8 -D 'view="base_top"' dial_spinner.scad
$S -o renders/clash.png        --imgsize=1200,900 --camera=0,-30,-165,0,0,28 -D 'view="clash"' -D 'fn_big=96' dial_spinner.scad
$S -o renders/section.png      --imgsize=1600,620 --camera=172,0,21,0,0,21 --projection=o -D 'view="section"' -D 'fn_big=96' dial_spinner.scad
$S -o renders/section_xz.png   --imgsize=1600,620 --camera=0,172,21,0,0,21 --projection=o -D 'view="section_xz"' -D 'fn_big=96' dial_spinner.scad
$S -o renders/nfc.png          --imgsize=1600,800 --camera=-42.74,15.34,33.2,-15.978,-14.386,33.2 --projection=o -D 'view="nfc"' -D 'fn_big=192' dial_spinner.scad
./export_stl.sh
$S -o renders/parts.png        --imgsize=1400,800 --camera=135,-380,520,135,-50,0 parts_plate.scad
python3 calcs.py > calcs_output.txt
{ echo "# clash_report.txt -- generated by check_clashes.sh (see legend at the end)"; ./check_clashes.sh 0
  echo "--- near misses (rotor envelope grown 0.3 mm) ---"; ./check_clashes.sh 0.3 | grep -E "^(CLASH|\?\?)" || true
  cat clash_legend.txt; } > clash_report.txt
cat clash_report.txt
