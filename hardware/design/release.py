#!/usr/bin/env python3
"""Produce fabrication + review outputs for each board into hardware/fab/<board>/.

usage: python3 hardware/design/release.py [--board main|base]

Outputs: gerbers.zip (+ gerbers/), JLCPCB BOM + CPL CSVs, schematic PDF,
board PDFs (copper/silk per side), and 3D renders (top/bottom).
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HW = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(HW, "tools"))

import fab  # noqa: E402
import jlc_cpl  # noqa: E402

BOARDS = {"main": 4, "base": 4}


def render3d(pcb, png, side, zoom=1.0):
    cmd = ["kicad-cli", "pcb", "render", "-o", png, "--width", "1400", "--height", "1400", "--side", side,
           "--background", "opaque", "--quality", "high", "--zoom", str(zoom), pcb]
    if shutil.which("xvfb-run"):
        cmd = ["xvfb-run", "-a"] + cmd
    subprocess.run(cmd, capture_output=True, timeout=600)
    return png


def board_pdf(pcb, pdf, layers):
    subprocess.run(["kicad-cli", "pcb", "export", "pdf", "--layers", ",".join(layers), "--mode-single",
                    "--include-border-title", "-o", pdf, pcb], capture_output=True)
    return pdf


def sync_fields(pcb, net):
    """Copy value/MPN/LCSC/Manufacturer from the (re-exported) netlist onto the board footprints."""
    import pcbnew
    import pcbgen
    comps, _ = pcbgen.load_netlist(net)
    b = pcbnew.LoadBoard(pcb)
    changed = 0
    for fp in b.GetFootprints():
        c = comps.get(fp.GetReference())
        if not c:
            continue
        if fp.GetValue() != c["value"]:
            fp.SetValue(c["value"])
            changed += 1
        dnp = "dnp" in c["props"] or bool(c["fields"].get("DNP"))
        if fp.IsDNP() != dnp:
            fp.SetDNP(dnp)
            changed += 1
        attrs = fp.GetAttributes()
        want = attrs & ~(pcbnew.FP_EXCLUDE_FROM_BOM | pcbnew.FP_EXCLUDE_FROM_POS_FILES)
        if "exclude_from_bom" in c["props"]:
            want |= pcbnew.FP_EXCLUDE_FROM_BOM | pcbnew.FP_EXCLUDE_FROM_POS_FILES
        if want != attrs and not attrs & pcbnew.FP_BOARD_ONLY:
            fp.SetAttributes(want)
            changed += 1
        for k in ("MPN", "LCSC", "Manufacturer"):
            v = c["fields"].get(k)
            current = fp.GetFieldText(k) if fp.HasFieldByName(k) else None
            if v and current != v:
                fp.SetField(k, v)
                fld = fp.GetFieldByName(k)
                if fld:
                    fld.SetVisible(False)
                changed += 1
    if changed:
        pcbnew.SaveBoard(pcb, b)
    return changed


def gate(pcb, out):
    """Refuse to release a board that fails DRC or no longer matches its schematic."""
    rpt = os.path.join(out, "drc-parity.rpt")
    r = subprocess.run(["kicad-cli", "pcb", "drc", "--schematic-parity", "--severity-error",
                        "--exit-code-violations", "-o", rpt, pcb], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"DRC/parity violations in {pcb} - see {rpt}; refusing to write fab outputs "
                         "(use --force for a review-only package)")


def order_notes(pcb, net, path):
    import pcbnew
    import pcbgen
    comps, _ = pcbgen.load_netlist(net)
    b = pcbnew.LoadBoard(pcb)
    dnp = sorted((r for r, c in comps.items() if "dnp" in c["props"] or c["fields"].get("DNP")), key=fab._refkey)
    bottom = sorted((fp.GetReference() for fp in b.GetFootprints()
                     if fp.IsFlipped() and not fp.GetAttributes() & pcbnew.FP_EXCLUDE_FROM_POS_FILES
                     and not fp.IsDNP()), key=fab._refkey)
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"# Order notes: {os.path.basename(pcb)}\n\n(generated by hardware/design/release.py; do not edit)\n\n")
        f.write(f"* Do not place (DNP), excluded from BOM/CPL: {', '.join(dnp) or 'none'}\n")
        f.write(f"* Bottom-side placements ({len(bottom)}): {', '.join(bottom) or 'none'}\n")
        f.write("* CPL angles and origins include the JLC library corrections from hardware/design/jlc_offsets.json "
                "(top: θ+α, bottom: 180−θ+α). Every row was checked by putting the EasyEDA pads down at its point and "
                "angle: all land on copper. Still check every IC and connector in JLC's placement preview.\n")
        f.write(f"* Board-only parts (no BOM): {', '.join(sorted(fp.GetReference() for fp in b.GetFootprints() if fp.GetAttributes() & pcbnew.FP_BOARD_ONLY))}\n")
    return path


def release(board, force=False):
    kdir = os.path.join(HW, "kicad", board)
    proj = f"dial-me-spinner-{board}"
    pcb = os.path.join(kdir, proj + ".kicad_pcb")
    sch = os.path.join(kdir, proj + ".kicad_sch")
    net = os.path.join(kdir, proj + ".net")
    subprocess.run(["kicad-cli", "sch", "export", "netlist", "-o", net, sch], check=True, capture_output=True)
    print(f"[{board}] synced {sync_fields(pcb, net)} footprint fields from the schematic")
    out = os.path.join(HW, "fab", board)
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)
    tmp = os.path.join(out, ".tmp")
    os.makedirs(tmp)
    if not force:
        gate(pcb, out)
    fab.gerbers(pcb, out, BOARDS[board])
    fab.jlc_bom(net, os.path.join(out, f"{proj}-BOM-JLCPCB.csv"))
    _, _, _, notes = jlc_cpl.write_cpl(pcb, os.path.join(out, f"{proj}-CPL-JLCPCB.csv"),
                                       {"dial_spinner": os.path.join(kdir, "lib", "dial_spinner.pretty")})
    print(f"[{board}] CPL: every JLC pad lands on copper" + "".join(f"\n  note: {n}" for n in notes))
    order_notes(pcb, net, os.path.join(out, "ORDER-NOTES.md"))
    subprocess.run(["kicad-cli", "sch", "export", "pdf", "-o", os.path.join(out, f"{proj}-schematic.pdf"), sch],
                   capture_output=True)
    cu = ["F.Cu", "In1.Cu", "In2.Cu", "B.Cu"] if BOARDS[board] == 4 else ["F.Cu", "B.Cu"]
    board_pdf(pcb, os.path.join(out, f"{proj}-top.pdf"), ["F.Cu", "F.Silkscreen", "F.Fab", "Edge.Cuts"])
    board_pdf(pcb, os.path.join(out, f"{proj}-bottom.pdf"), ["B.Cu", "B.Silkscreen", "B.Fab", "Edge.Cuts"])
    for layer in cu:
        board_pdf(pcb, os.path.join(out, f"{proj}-{layer.replace('.', '_')}.pdf"), [layer, "Edge.Cuts"])
    render3d(pcb, os.path.join(out, f"{proj}-3d-top.png"), "top")
    render3d(pcb, os.path.join(out, f"{proj}-3d-bottom.png"), "bottom")
    shutil.rmtree(tmp)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--board", choices=sorted(BOARDS))
    ap.add_argument("--force", action="store_true", help="skip the DRC/parity gate (review-only package)")
    a = ap.parse_args()
    for b in BOARDS:
        if a.board and b != a.board:
            continue
        print(f"[{b}] ->", release(b, a.force))


if __name__ == "__main__":
    main()
